# دسته‌بند موضوع نظر مشتریان - نسخه خیلی ساده
# موضوعات: قیمت، کیفیت، ارسال، پشتیبانی، طراحی
# ============================================

def predict_topic(text):
    text = text.strip()

    scores = {
        "ارسال": 0,
        "قیمت": 0,
        "کیفیت": 0,
        "طراحی": 0,
        "پشتیبانی": 0,
    }

    keywords = {
        "ارسال": [
            "دیر", "زود", "ارسال", "پست", "پیک",
            "رسید", "بسته", "تحویل", "آوردن", "بسته‌بندی"
        ],
        "قیمت": [
            "قیمت", "گرون", "ارزون", "ارزش", "پول",
            "هزینه", "مناسب", "گران"
        ],
        "کیفیت": [
            "کیفیت", "جنس", "مقاوم", "خراب", "شکست",
            "دوام", "ضعیف", "عالی", "ساخت"
        ],
        "طراحی": [
            "طراحی", "ظاهر", "رنگ", "زیبا", "قشنگ",
            "شکل", "جذاب", "شیک"
        ],
        "پشتیبانی": [
            "پشتیبانی", "پاسخ", "تماس", "پاسخگو",
            "خدمات", "جواب", "مشکل"
        ],
    }

    for topic, words in keywords.items():
        for w in words:
            if w in text:
                scores[topic] += 1

    if max(scores.values()) == 0:
        return "نامشخص"

    return max(scores, key=scores.get)


