if __name__ == "__main__":
    tests = [
        "خیلی دیر به دستم رسید",
        "جنسش نسبت به قیمتش خوبه",
        "رنگ و ظاهرش خیلی قشنگه",
        "پشتیبانی جوابم رو نداد",
        "قیمتش خیلی گرونه",
        "کیفیتش عالیه",
        "ارسال سریع بود",
        "ظاهر محصول خیلی جذابه",
        "پشتیبانی مشکل من رو حل کرد",
        "بسته‌بندی خراب بود و دیر رسید",
    ]

    print("=" * 50)
    print("نتایج:")
    print("=" * 50)

    for t in tests:
        result = predict_topic(t)
        print(f"نظر: {t}")
        print(f"→ موضوع: {result}")
        print("-" * 40)
